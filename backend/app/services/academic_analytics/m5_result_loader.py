import json
from pathlib import Path


class M5ResultLoader:
    """
    M5.1 — Result Loader

    Loads the output generated by M4.

    M4 produces one JSON file per PYQ paper:

        BCS_302_ENDTERM_analysis.json
        BCS_302_MIDTERM_analysis.json
        ...

    Each file contains:

        question
        analysis

    M5.1 combines all successful analyses into one clean
    list that can be consumed by the remaining M5 modules.

    Important:
    Failed M4 questions have:

        "analysis": null

    Those questions are skipped here.

    M5 therefore works with whatever successful M4 results
    are currently available.
    """

    def __init__(self, analysis_dir: Path):
        """
        Parameters
        ----------
        analysis_dir:
            Directory containing M4 *_analysis.json files.
        """

        self.analysis_dir = Path(
            analysis_dir
        )

    # ======================================================
    # LOAD ONE FILE
    # ======================================================

    def load_file(
        self,
        file_path: Path,
    ) -> list[dict]:
        """
        Load one M4 analysis JSON file.

        Returns
        -------
        list[dict]
            Successful question-analysis records.

        Failed records are ignored.
        """

        # --------------------------------------------------
        # READ JSON
        # --------------------------------------------------

        with open(
            file_path,
            "r",
            encoding="utf-8",
        ) as file:

            data = json.load(file)

        # --------------------------------------------------
        # EXTRACT QUESTIONS
        # --------------------------------------------------

        questions = data.get(
            "questions",
            []
        )

        successful_records = []

        # --------------------------------------------------
        # KEEP ONLY SUCCESSFUL ANALYSES
        # --------------------------------------------------

        for item in questions:

            analysis = item.get(
                "analysis"
            )

            # M4 failed this question.
            #
            # We don't want it to enter the analytics
            # calculations.

            if analysis is None:
                continue

            question = item.get(
                "question"
            )

            # A valid M4 result should contain both.
            if question is None:
                continue

            successful_records.append(
                {
                    "question": question,
                    "analysis": analysis,
                }
            )

        return successful_records

    # ======================================================
    # LOAD ALL FILES
    # ======================================================

    def load_all(self) -> list[dict]:
        """
        Load all M4 analysis files from the analysis directory.

        Returns
        -------
        list[dict]
            Combined successful M4 results from all papers.
        """

        # --------------------------------------------------
        # VALIDATE DIRECTORY
        # --------------------------------------------------

        if not self.analysis_dir.exists():

            raise FileNotFoundError(
                "M4 analysis directory does not exist: "
                f"{self.analysis_dir}"
            )

        # --------------------------------------------------
        # FIND ANALYSIS FILES
        # --------------------------------------------------

        files = sorted(
            self.analysis_dir.glob(
                "*_analysis.json"
            )
        )

        if not files:

            raise FileNotFoundError(
                "No M4 analysis files found in: "
                f"{self.analysis_dir}"
            )

        # --------------------------------------------------
        # LOAD ALL FILES
        # --------------------------------------------------

        all_results = []

        for file_path in files:

            results = self.load_file(
                file_path
            )

            all_results.extend(
                results
            )

        return all_results

    # ======================================================
    # GET FILE COUNT
    # ======================================================

    def get_file_count(self) -> int:
        """
        Return the number of M4 analysis files.
        """

        if not self.analysis_dir.exists():
            return 0

        return len(
            list(
                self.analysis_dir.glob(
                    "*_analysis.json"
                )
            )
        )

    # ======================================================
    # GET SUCCESS COUNT
    # ======================================================

    def get_success_count(self) -> int:
        """
        Return the number of successfully analyzed
        questions across all M4 files.
        """

        results = self.load_all()

        return len(results)