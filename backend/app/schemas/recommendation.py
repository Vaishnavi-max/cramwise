class RecommendedTopic(BaseModel):
    """
    One topic recommended by the LLM.
    """

    topic_id: str = Field(
        description=(
            "Must exactly match one of the supplied "
            "candidate topic IDs."
        )
    )

    study_order: int = Field(
        ge=1,
        description="Order in which the student should study the topic."
    )

    recommended_minutes: int = Field(
        gt=0,
        description="Recommended study time in minutes."
    )

    reason: str = Field(
        min_length=1,
        description="Short explanation for recommending this topic."
    )


class PersonalizedRecommendation(BaseModel):
    """
    Structured recommendation generated by M6.3.
    """

    recommendations: list[RecommendedTopic] = Field(
        default_factory=list
    )

    total_minutes: int = Field(
        ge=0
    )